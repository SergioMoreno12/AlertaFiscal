"""
Phase 2 - reproducibility log.

Writes docs/02_run_log.md with the environment, the SHA-256 of every raw and processed file,
and the output of check_dataset.py. Run it AFTER the four pipeline scripts, from the repository
root, inside a clean virtual environment:
    python ml/src/make_run_log.py
"""

import hashlib
import platform
import subprocess
import sys
from datetime import datetime
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RAW_DIR = ROOT / "ml" / "data" / "raw"
PROCESSED_DIR = ROOT / "ml" / "data" / "processed"
OUTPUT = ROOT / "docs" / "02_run_log.md"
PACKAGES = ["pandas", "numpy", "openpyxl"]


def sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def hash_table(folder):
    rows = ["| File | SHA-256 |", "|---|---|"]
    for path in sorted(folder.iterdir()):
        if path.is_file() and path.name != ".gitkeep":
            rows.append(f"| `{path.name}` | `{sha256(path)}` |")
    return "\n".join(rows)


def main():
    now = datetime.now()
    in_venv = sys.prefix != sys.base_prefix
    versions = []
    for name in PACKAGES:
        try:
            versions.append(f"| {name} | {metadata.version(name)} |")
        except metadata.PackageNotFoundError:
            versions.append(f"| {name} | not installed |")

    check = subprocess.run(
        [sys.executable, str(ROOT / "ml" / "src" / "check_dataset.py")],
        capture_output=True, text=True, cwd=ROOT,
    )
    check_output = (check.stdout + check.stderr).strip()

    text = f"""# Run Log (Phase 2)

Generated by `ml/src/make_run_log.py`. Do not edit by hand: run the script again instead.

## Environment

| Item | Value |
|---|---|
| Date | {now:%B} {now.day}, {now.year} |
| Operating system | {platform.platform()} |
| Python | {platform.python_version()} |
| Run inside a virtual environment | {"yes" if in_venv else "NO (create one and run again)"} |

| Package | Version |
|---|---|
{chr(10).join(versions)}

## SHA-256 of the raw files (`ml/data/raw/`, not committed)

{hash_table(RAW_DIR)}

## SHA-256 of the processed files (`ml/data/processed/`)

{hash_table(PROCESSED_DIR)}

The processed hashes depend on the line endings of the machine (Windows writes CRLF, Linux writes LF). The content is identical; compare hashes only between runs on the same operating system.

## Output of `check_dataset.py`

Exit code: {check.returncode}

```
{check_output}
```
"""
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    if check.returncode != 0:
        sys.exit(1)


if __name__ == "__main__":
    main()